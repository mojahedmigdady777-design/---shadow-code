    /**
     * Serialized strings stored inside Firestore `/gameContent/{packId}` documents.
     */
    fun serializeWordsPackEntries(): List<String> {
        val list = mutableListOf<String>()
        builtInExtraActions.forEach { list += "ACTION|$it" }
        builtInExtraLocations.forEach { list += "LOCATION|$it" }
        builtInExtraDurations.forEach { list += "DURATION|$it" }
        builtInExtraThreats.forEach { list += "THREAT|$it" }
        builtInExtraReasons.forEach { list += "REASON|$it" }
        builtInExtraSuspicions.forEach { list += "SUSPICION|$it" }
        builtInExtraSectors.forEach { list += "SECTOR|$it" }
        return list
    }

    fun applyCloudWordsPack(entries: List<String>) {
        val actions = mutableListOf<String>()
        val locs = mutableListOf<String>()
        val durs = mutableListOf<String>()
        val threats = mutableListOf<String>()
        val reasons = mutableListOf<String>()
        val susps = mutableListOf<String>()
        val secs = mutableListOf<String>()
        entries.forEach { raw ->
            val parts = raw.split("|", limit = 2)
            if (parts.size == 2) {
                when (parts[0]) {
                    "ACTION" -> actions += parts[1]
                    "LOCATION" -> locs += parts[1]
                    "DURATION" -> durs += parts[1]
                    "THREAT" -> threats += parts[1]
                    "REASON" -> reasons += parts[1]
                    "SUSPICION" -> susps += parts[1]
                    "SECTOR" -> secs += parts[1]
                }
            }
        }
        cloudExtraActions = actions
        cloudExtraLocations = locs
        cloudExtraDurations = durs
        cloudExtraThreats = threats
        cloudExtraReasons = reasons
        cloudExtraSuspicions = susps
        cloudExtraSectors = secs
    }

    fun serializePuzzlesPackEntries(): List<String> {
        val list = mutableListOf<String>()
        builtInCipherWords.forEach { list += "CIPHER|$it" }
        builtInAlgorithmScenarios.forEach { s ->
            list += "ALGO|${s.id}|${s.title}|${s.steps.joinToString("~")}|${s.clues.joinToString("~")}"
        }
        builtInDeductionScenarios.forEach { d ->
            list += "DEDUCT|${d.id}|${d.entities.joinToString("~")}|${d.locations.joinToString("~")}"
        }
        return list
    }

    fun applyCloudPuzzlesPack(entries: List<String>) {
        val ciphers = mutableListOf<String>()
        val algos = mutableListOf<AlgorithmScenarioSeed>()
        val deducts = mutableListOf<DeductionScenarioSeed>()
        entries.forEach { raw ->
            val parts = raw.split("|")
            when (parts.firstOrNull()) {
                "CIPHER" -> if (parts.size >= 2) ciphers += parts[1]
                "ALGO" -> if (parts.size >= 5) {
                    algos += AlgorithmScenarioSeed(
                        id = parts[1],
                        title = parts[2],
                        steps = parts[3].split("~"),
                        clues = parts[4].split("~")
                    )
                }
                "DEDUCT" -> if (parts.size >= 4) {
                    deducts += DeductionScenarioSeed(
                        id = parts[1],
                        entities = parts[2].split("~"),
                        locations = parts[3].split("~")
                    )
                }
            }
        }
        cloudCipherWords = ciphers
        cloudAlgorithmScenarios = algos
        cloudDeductionScenarios = deducts
    }

    fun serializeSpyReportsPackEntries(): List<String> {
        return builtInSpyReports.map { "${it.id}|${it.text}" }
    }

    fun applyCloudSpyReportsPack(entries: List<String>) {
        cloudSpyReports = entries.mapNotNull { raw ->
            val parts = raw.split("|", limit = 2)
            if (parts.size == 2) SpyReportSeed(parts[0], parts[1]) else null
        }
    }
